-- VERCETTI voice rooms: run once in Supabase SQL Editor.
-- Safe to re-run: the table is created only when missing and policies are replaced.

create table if not exists public.voice_rooms (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 40),
  max_participants integer,
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint voice_rooms_max_participants_check
    check (max_participants is null or max_participants between 2 and 100)
);

alter table public.voice_rooms enable row level security;

drop policy if exists "Authenticated users can view voice rooms" on public.voice_rooms;
create policy "Authenticated users can view voice rooms"
on public.voice_rooms
for select
to authenticated
using (true);

drop policy if exists "Staff can create voice rooms" on public.voice_rooms;
create policy "Staff can create voice rooms"
on public.voice_rooms
for insert
to authenticated
with check (
  created_by = (select auth.uid())
  and public.is_verceti_staff()
);

drop policy if exists "Staff can delete voice rooms" on public.voice_rooms;
create policy "Staff can delete voice rooms"
on public.voice_rooms
for delete
to authenticated
using (public.is_verceti_staff());

grant select, insert, delete on public.voice_rooms to authenticated;
grant usage, select on sequence public.voice_rooms_id_seq to authenticated;
